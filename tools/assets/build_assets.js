// Writes Engine-Sim-Assets.js from the files extracted out of engine-sim and
// delta-studio (see PROCEDENCIA.md):
//   node tools/assets/build_assets.js <slkscr.ttf> <outlines.json> <irs.json>
const fs = require('fs');
const path = require('path');
const [font, outlines, irs] = process.argv.slice(2);
const out = `/* Engine-Sim-Assets.js (generated by tools/assets/build_assets.js)
 * - font: Silkscreen by Jason Kottke (slkscr.ttf from delta-studio), base64.
 * - models: outlines of the meshes in engine-sim's assets/assets.ysce
 *   (Crankshaft, ConnectingRod, Piston, CylinderHead, Valve, CrankSnout,
 *   CrankSnoutThreads, Logo), one flat [x, y, ...] array per boundary loop.
 * - irs: engine-sim impulse responses (es/sound-library), int16 base64,
 *   clipped like Synthesizer::initializeImpulseResponse, with their volumes.
 * See PROCEDENCIA.md for licenses.
 */
const ES_ASSETS = {
  font: '${fs.readFileSync(font).toString('base64')}',
  models: ${fs.readFileSync(outlines, 'utf8').trim()},
  irs: ${fs.readFileSync(irs, 'utf8').trim()},
};
if (typeof module !== 'undefined') module.exports = { ES_ASSETS };
`;
fs.writeFileSync(path.join(__dirname, '..', '..', 'Engine-Sim-Assets.js'), out);
console.log('Engine-Sim-Assets.js written,', out.length, 'bytes');
